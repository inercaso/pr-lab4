async def check_consistency() -> dict[str, Any]:
    """
    verify data consistency across all nodes.
    compares all follower data with leader data.
    """
    print("\n--- checking data consistency ---")

    results: dict[str, Any] = {
        "leader_size": 0,
        "followers": {},
        "all_consistent": True,
        "details": [],
    }

    async with httpx.AsyncClient(timeout=30.0) as client:
        # get leader data
        try:
            leader_response = await client.get(f"{LEADER_URL}/store")
            leader_data = leader_response.json()
            results["leader_size"] = leader_data["size"]
            leader_store = leader_data["data"]
            print(f"  leader has {results['leader_size']} keys")
        except Exception as e:
            print(f"  failed to get leader data: {e}")
            results["error"] = str(e)
            return results

        # check each follower
        for name, url in FOLLOWER_URLS.items():
            try:
                response = await client.get(f"{url}/store")
                follower_data = response.json()
                follower_store = follower_data["data"]

                # compare with leader
                missing_keys = set(leader_store.keys()) - set(follower_store.keys())
                extra_keys = set(follower_store.keys()) - set(leader_store.keys())
                mismatched_values = []

                for key in set(leader_store.keys()) & set(follower_store.keys()):
                    if leader_store[key] != follower_store[key]:
                        mismatched_values.append(key)

                is_consistent = (
                    len(missing_keys) == 0
                    and len(extra_keys) == 0
                    and len(mismatched_values) == 0
                )

                results["followers"][name] = {
                    "size": follower_data["size"],
                    "consistent": is_consistent,
                    "missing_keys": len(missing_keys),
                    "extra_keys": len(extra_keys),
                    "mismatched_values": len(mismatched_values),
                }

                if not is_consistent:
                    results["all_consistent"] = False
                    results["details"].append(
                        f"{name}: missing={len(missing_keys)}, "
                        f"extra={len(extra_keys)}, "
                        f"mismatched={len(mismatched_values)}"
                    )

                status = "consistent" if is_consistent else "inconsistent"
                print(f"  {name}: {follower_data['size']} keys - {status}")

            except Exception as e:
                print(f"  {name}: error - {e}")
                results["followers"][name] = {"error": str(e)}
                results["all_consistent"] = False

    return results


async def check_race_condition_consistency(quorum: int) -> ConsistencyResult:
    """
    check consistency by comparing key values between leader and followers.

    measures the percentage of (key, follower) pairs where the values match.
    this captures race conditions from concurrent writes with network delays:
    - higher quorum = more followers have consistent data = higher %
    - lower quorum = more async replication = more race conditions = lower %

    args:
        quorum: the quorum value used for the benchmark (to filter keys)

    returns:
        ConsistencyResult with consistency percentage and per-follower breakdown
    """
    print(f"\n--- checking race condition consistency for quorum={quorum} ---")

    async with httpx.AsyncClient(timeout=30.0) as client:
        # get leader data
        try:
            leader_response = await client.get(f"{LEADER_URL}/store")
            leader_data = leader_response.json()
            leader_store = leader_data["data"]
        except Exception as e:
            print(f"  failed to get leader data: {e}")
            return ConsistencyResult(
                quorum=quorum,
                total_keys=0,
                total_comparisons=0,
                matching_values=0,
                consistency_percentage=0.0,
                per_follower_consistency={},
            )

        # filter keys for this quorum only (q{quorum}_k0, q{quorum}_k1, ...)
        quorum_keys = [k for k in leader_store.keys() if k.startswith(f"q{quorum}_")]
        total_keys = len(quorum_keys)

        if total_keys == 0:
            print(f"  no keys found for quorum={quorum}")
            return ConsistencyResult(
                quorum=quorum,
                total_keys=0,
                total_comparisons=0,
                matching_values=0,
                consistency_percentage=0.0,
                per_follower_consistency={},
            )

        print(f"  leader has {total_keys} keys for quorum={quorum}")

        # count matching key-value pairs across all followers
        total_comparisons = 0
        matching_values = 0
        per_follower_consistency: dict[str, float] = {}

        for name, url in FOLLOWER_URLS.items():
            try:
                response = await client.get(f"{url}/store")
                follower_data = response.json()
                follower_store = follower_data["data"]

                # count how many keys match for this follower
                follower_matches = 0
                for key in quorum_keys:
                    total_comparisons += 1
                    if leader_store.get(key) == follower_store.get(key):
                        matching_values += 1
                        follower_matches += 1

                follower_pct = (follower_matches / total_keys) * 100
                per_follower_consistency[name] = follower_pct
                print(
                    f"  {name}: {follower_matches}/{total_keys} keys match ({follower_pct:.1f}%)"
                )

            except Exception as e:
                print(f"  {name}: error - {e}")
                per_follower_consistency[name] = 0.0

        # overall consistency = matching / total comparisons
        consistency_pct = (
            (matching_values / total_comparisons) * 100
            if total_comparisons > 0
            else 0.0
        )

        print(
            f"  overall: {matching_values}/{total_comparisons} = {consistency_pct:.1f}%"
        )

        return ConsistencyResult(
            quorum=quorum,
            total_keys=total_keys,
            total_comparisons=total_comparisons,
            matching_values=matching_values,
            consistency_percentage=consistency_pct,
            per_follower_consistency=per_follower_consistency,
        )


def restart_docker(quorum: int) -> bool:
    """restart docker-compose with specific quorum."""
    print(f"\n  restarting docker with quorum={quorum}...")

    try:
        # write the .env file with new quorum
        write_env_file(quorum)

        # stop existing containers
        subprocess.run(
            ["docker-compose", "down"],
            capture_output=True,
            check=True,
            cwd=PROJECT_ROOT,
        )

        # start with new quorum (will read from .env file)
        subprocess.run(
            ["docker-compose", "up", "-d"],  # "--build"],
            capture_output=True,
            check=True,
            cwd=PROJECT_ROOT,
        )

        return True

    except subprocess.CalledProcessError as e:
        print(f"  docker command failed: {e}")
        return False
    except Exception as e:
        print(f"  failed to restart: {e}")
        return False


