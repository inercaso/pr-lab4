def plot_consistency_comparison(
    basic_results: list[ConsistencyResult],
    versioned_results: list[ConsistencyResult],
    output_path: str,
) -> None:
    """
    generate and save a comparison plot showing both modes on the same chart.

    compares:
    - red line: basic mode (race conditions)
    - green line: versioned mode (no race conditions)
    """
    quorums = [r.quorum for r in basic_results]
    basic_consistency = [r.consistency_percentage for r in basic_results]
    versioned_consistency = [r.consistency_percentage for r in versioned_results]

    plt.figure(figsize=(10, 6))

    # plot basic consistency (red)
    plt.plot(
        quorums,
        basic_consistency,
        color="#F44336",
        linestyle="-",
        linewidth=2,
        marker="o",
        markersize=8,
        label="Basic (Last-Writer-Wins)",
    )

    # plot versioned consistency (green)
    plt.plot(
        quorums,
        versioned_consistency,
        color="#4CAF50",
        linestyle="-",
        linewidth=2,
        marker="s",
        markersize=8,
        label="Versioned (Conflict Resolution)",
    )

    plt.xlabel("Write Quorum", fontsize=12)
    plt.ylabel("Consistency (%)", fontsize=12)
    plt.title(
        "Data Consistency Comparison: Basic vs Versioned\n"
        f"({NUM_KEYS * WRITES_PER_KEY} concurrent writes, "
        f"network delay: [{DELAY_MIN}ms, {DELAY_MAX}ms])",
        fontsize=14,
    )
    plt.xticks(quorums)
    plt.ylim(0, 105)
    plt.legend(loc="center right", fontsize=10)
    plt.grid(True, alpha=0.3)

    # add value annotations for basic
    for q, basic, versioned in zip(quorums, basic_consistency, versioned_consistency):
        plt.annotate(
            f"{basic:.0f}%",
            (q, basic),
            textcoords="offset points",
            xytext=(0, -15),
            ha="center",
            fontsize=9,
            color="#F44336",
        )
        # only annotate versioned if different from basic
        if abs(versioned - basic) > 5:
            plt.annotate(
                f"{versioned:.0f}%",
                (q, versioned),
                textcoords="offset points",
                xytext=(0, 10),
                ha="center",
                fontsize=9,
                color="#4CAF50",
            )

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()

    print(f"  saved: {output_path}")


def generate_report(
    results: list[BenchmarkResult],
    consistency: dict[str, Any],
    consistency_results: list[ConsistencyResult] | None = None,
) -> str:
    """generate text report."""
    lines = []
    lines.append("=" * 80)
    lines.append("PERFORMANCE ANALYSIS REPORT")
    lines.append("distributed key-value store with single-leader replication")
    lines.append("=" * 80)
    lines.append("")

    lines.append("CONFIGURATION:")
    lines.append(f"  total writes per quorum: {NUM_KEYS * WRITES_PER_KEY}")
    lines.append(f"  number of keys per quorum: {NUM_KEYS}")
    lines.append(f"  writes per key: {WRITES_PER_KEY}")
    lines.append(f"  concurrent batch size: {CONCURRENT_BATCH_SIZE}")
    lines.append(f"  network delay: [{DELAY_MIN}ms, {DELAY_MAX}ms]")
    lines.append(f"  number of followers: {NUM_FOLLOWERS}")
    lines.append("")

    lines.append("LATENCY RESULTS BY QUORUM:")
    lines.append("-" * 80)
    lines.append(
        f"{'quorum':<8}{'mean (ms)':<12}{'median (ms)':<14}{'p90 (ms)':<12}{'p95 (ms)':<12}{'success':<10}"
    )
    lines.append("-" * 80)

    for r in sorted(results, key=lambda x: x.quorum):
        lines.append(
            f"{r.quorum:<8}{r.avg_latency_ms:<12.2f}{r.median_latency_ms:<14.2f}"
            f"{r.p90_latency_ms:<12.2f}{r.p95_latency_ms:<12.2f}{r.successful_writes}/{r.total_writes}"
        )

    lines.append("-" * 80)
    lines.append("")

    lines.append("PERCENTILE EXPLANATION:")
    lines.append("-" * 80)
    lines.append("  - Mean: average of all latency measurements")
    lines.append("  - Median (p50): 50% of requests completed faster than this")
    lines.append("  - p90: 90% of requests completed faster than this")
    lines.append("  - p95: 95% of requests completed faster than this (tail latency)")
    lines.append("")
    lines.append("  p90 and p95 are important for understanding worst-case behavior.")
    lines.append("  high tail latencies indicate occasional slow responses.")
    lines.append("")

    lines.append("WHY LATENCY INCREASES WITH QUORUM:")
    lines.append("-" * 80)
    lines.append("  with quorum-based replication, the leader waits for K followers")
    lines.append("  to acknowledge before responding. each follower has random delay.")
    lines.append("")
    lines.append("  - quorum=1: wait for FASTEST follower only (low latency)")
    lines.append("  - quorum=3: wait for 3rd fastest (median latency)")
    lines.append("  - quorum=5: wait for SLOWEST follower (high latency)")
    lines.append("")
    lines.append("  this is the consistency vs latency trade-off:")
    lines.append("  - higher quorum = more durable (data on more nodes)")
    lines.append("  - higher quorum = higher latency (wait for slower nodes)")
    lines.append("")

    # race condition consistency results (per quorum)
    if consistency_results:
        lines.append("CONSISTENCY BY QUORUM:")
        lines.append("-" * 80)
        lines.append(
            f"{'quorum':<8}{'consistency (%)':<18}{'matching':<15}{'total':<10}"
        )
        lines.append("-" * 80)

        for cr in sorted(consistency_results, key=lambda x: x.quorum):
            lines.append(
                f"{cr.quorum:<8}{cr.consistency_percentage:<18.1f}"
                f"{cr.matching_values:<15}{cr.total_comparisons:<10}"
            )

        lines.append("-" * 80)
        lines.append("")

        lines.append("CONSISTENCY EXPLANATION:")
        lines.append("-" * 80)
        lines.append(
            "  consistency = % of (key, follower) pairs where values match leader."
        )
        lines.append(
            "  race conditions from concurrent writes + network delays cause mismatches."
        )
        lines.append("")

    lines.append("EVENTUAL CONSISTENCY (FINAL STATE):")
    lines.append("-" * 80)
    if consistency.get("all_consistent", False):
        lines.append("  all replicas are consistent with leader")
    else:
        lines.append("  some replicas have inconsistencies:")
        for detail in consistency.get("details", []):
            lines.append(f"    - {detail}")
    lines.append("")

    lines.append(f"  leader: {consistency.get('leader_size', 'n/a')} keys")
    for name, data in consistency.get("followers", {}).items():
        if "error" in data:
            lines.append(f"  {name}: error - {data['error']}")
        else:
            status = "consistent" if data.get("consistent") else "inconsistent"
            lines.append(f"  {name}: {data.get('size', 'n/a')} keys - {status}")
    lines.append("")

    lines.append("CONSISTENCY EXPLANATION:")
    lines.append("-" * 80)
    lines.append("  semi-synchronous replication guarantees:")
    lines.append("  - data is on leader + quorum followers BEFORE write returns")
    lines.append("  - remaining followers receive data asynchronously (eventually)")
    lines.append("")

    return "\n".join(lines)


